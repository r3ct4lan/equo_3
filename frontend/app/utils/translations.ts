export function translate(locale: AppLocale, text: string): string {
  if (locale === 'en') return text
  const connected = /^You are already connected with (.+)\.$/u.exec(text)
  if (connected) return `У вас уже есть связь с ${connected[1]}.`
  return russian[text] ?? text
}

export function translateError(locale: AppLocale, text: string): string {
  if (locale === 'en') return text
  const seconds = /^Try again in (\d+) seconds?\.$/u.exec(text)
  if (seconds) return `Повторите попытку через ${seconds[1]} сек.`
  if (Object.values(russian).includes(text)) return text
  return russian[text] ?? 'Не удалось выполнить запрос. Проверьте данные и попробуйте снова.'
}
